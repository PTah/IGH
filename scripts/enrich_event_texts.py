def apply_book(path: Path) -> int:
    data = json.loads(path.read_text(encoding="utf-8"))
    n = 0
    for e in data.get("events", []):
        eid = e.get("id")
        if not eid:
            continue
        patch = PATCH.get(eid)
        if not patch:
            continue
        for k, v in patch.items():
            if v is None or v == "":
                continue
            if e.get(k) != v:
                e[k] = v
                n += 1
    write_json(path, data)
    return n


def main() -> None:
    total = 0
    for name in ("book01_curated.json", "book02_curated.json", "book03_curated.json"):
        c = apply_book(EXTRACTED / name)
        print(f"{name}: {c} field updates")
        total += c
    print("total field updates", total)


if __name__ == "__main__":
    main()
